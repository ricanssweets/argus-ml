/**
 * Central data-provenance UI. Every surface that can display a number renders
 * one of these:
 *  - `SyntheticTag`  — small inline pill placed ADJACENT to the numbers/cards.
 *  - `DemoBadge`     — page-header badge: "DEMO DATA · synthetic" (matches the
 *                      README promise) plus the reason the live call failed.
 *  - `DataErrorBanner` — loud banner spelling out config/network/timeout/HTTP.
 *
 * `provenanceOf` is the single decision point so no page can invent its own
 * (weaker) notion of "is this synthetic?".
 */
import type { DataError, Meta } from "@/lib/types";

export const SYNTHETIC_LABEL = "DEMO DATA · synthetic";

export interface Provenance {
  /** True when ANY of the envelopes is synthetic (or failed and fell back). */
  demo: boolean;
  /** First recorded failure reason, if any. */
  error: DataError | null;
  /** True when the API answered successfully but returned no records. */
  empty: boolean;
  asOf: string;
}

export function provenanceOf(
  ...metas: (Meta | undefined | null)[]
): Provenance {
  const list = metas.filter((m): m is Meta => Boolean(m));
  const error =
    list.map((m) => m.error).find((e): e is DataError => Boolean(e)) ?? null;
  return {
    demo: list.some((m) => m.demo === true) || error !== null,
    error,
    empty: list.some((m) => m.empty === true),
    asOf: list.map((m) => m.as_of).find((s) => Boolean(s)) ?? "",
  };
}

export function describeError(error: DataError): string {
  switch (error.kind) {
    case "config":
      return "No API URL configured for this build";
    case "network":
      return "API unreachable (network / DNS / connection refused)";
    case "timeout":
      return "API timed out before responding";
    case "http":
      return `API rejected the request: ${error.message}`;
    case "bad_envelope":
      return `Malformed API response: ${error.message}`;
    case "empty":
      return `API returned no records: ${error.message}`;
    default:
      return error.message;
  }
}

/** Small inline marker to place next to any synthetic number. */
export function SyntheticTag({
  className = "",
  label = "DEMO · synthetic",
}: {
  className?: string;
  label?: string;
}) {
  return (
    <span
      className={`inline-flex items-center gap-1 rounded border border-amber-500/50 bg-amber-500/15 px-1.5 py-0.5 text-[10px] font-bold uppercase tracking-[0.12em] text-amber-300 ${className}`}
      title="This figure is synthetic demo data generated by lib/demo-data.ts — it is NOT market data."
    >
      {label}
    </span>
  );
}

/** Page-header badge: unmistakable label + why live data is absent. */
export function DemoBadge({
  asOf,
  error,
  className = "",
}: {
  asOf?: string;
  error?: DataError | null;
  className?: string;
}) {
  return (
    <div className={`flex flex-col items-start gap-1 sm:items-end ${className}`}>
      <span className="inline-flex items-center gap-2 rounded-full border-2 border-amber-500/60 bg-amber-500/15 px-3 py-1 text-xs font-bold uppercase tracking-[0.16em] text-amber-200">
        <span className="h-2 w-2 animate-pulse rounded-full bg-amber-400" />
        {SYNTHETIC_LABEL}
      </span>
      <span className="text-xs text-amber-200/80">
        Not market data — every figure on this page is fabricated by the
        deterministic demo generator.
        {asOf ? ` Sample as of ${asOf} UTC.` : ""}
      </span>
      {error && (
        <span className="text-xs text-rose-300">
          Live feed unavailable: {describeError(error)}
        </span>
      )}
    </div>
  );
}

/** Loud banner for a failed/absent live feed. */
export function DataErrorBanner({
  error,
  empty,
  className = "",
}: {
  error?: DataError | null;
  empty?: boolean;
  className?: string;
}) {
  if (!error && !empty) return null;
  return (
    <div
      className={`rounded-lg border px-4 py-3 text-sm ${
        error
          ? "border-rose-500/50 bg-rose-500/10 text-rose-100"
          : "border-amber-500/40 bg-amber-500/10 text-amber-100"
      } ${className}`}
      role={error ? "alert" : "status"}
    >
      {error ? (
        <>
          <p className="font-bold uppercase tracking-wide">
            Live data unavailable — showing {SYNTHETIC_LABEL}
          </p>
          <p className="mt-1 text-xs">
            Reason ({error.kind}
            {error.status ? ` ${error.status}` : ""}): {describeError(error)}
          </p>
        </>
      ) : (
        <p className="text-xs">
          The API answered successfully but returned no records.
        </p>
      )}
    </div>
  );
}
